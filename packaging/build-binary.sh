#!/bin/sh
# Builds the agent as one self-contained executable per Linux architecture:
# the agent bundled into a single script and embedded in the official
# Node.js binary as a single executable application (SEA). A host with no
# Node.js and no Docker, which describes most database servers, can then run
# the agent with nothing else installed. Packaging only: nothing here
# publishes. build-release.sh calls this and lists the outputs in
# SHA256SUMS beside the tarball.
#
#   apps/agent/packaging/build-binary.sh
#
# Output, in apps/agent/packaging/out/:
#   realuptime-agent-<ver>-linux-x64
#   realuptime-agent-<ver>-linux-arm64
#
# The Node.js release is pinned (NODE_VERSION below) and every download is
# checked against nodejs.org's SHASUMS256.txt for that release. The SEA blob
# is generated by that same pinned Node.js, run for the build machine's own
# platform, because a blob only loads in the exact Node.js version that
# produced it.
set -eu

NODE_VERSION="${REALUPTIME_AGENT_NODE_VERSION:-22.22.0}"
TARGETS="${REALUPTIME_AGENT_BINARY_TARGETS:-linux-x64 linux-arm64}"
NODE_DIST="https://nodejs.org/dist/v$NODE_VERSION"
# postject writes the blob into the binary's resource section; the fuse is
# the sentinel string Node.js checks at startup (nodejs.org/api/single-executable-applications.html).
POSTJECT="postject@1.0.0-alpha.6"
# Build tools only, run pinned through npx so they never become agent
# dependencies (agent's runtime test keeps that list at zero).
ESBUILD="esbuild@0.28.2"
SEA_FUSE="NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2"

HERE="$(cd "$(dirname "$0")" && pwd)"
AGENT="$(cd "$HERE/.." && pwd)"
OUT="$HERE/out"
VERSION="$(node -p "require('$AGENT/package.json').version")"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT"

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}'; else shasum -a 256 "$1" | awk '{print $1}'; fi
}

curl -fsSL -o "$WORK/SHASUMS256.txt" "$NODE_DIST/SHASUMS256.txt"

# Downloads and unpacks one official Node.js build, verified against the
# release's SHASUMS256.txt, and prints the path of its node binary.
fetch_node() {
  name="node-v$NODE_VERSION-$1"
  file="$name.tar.gz"
  curl -fsSL -o "$WORK/$file" "$NODE_DIST/$file"
  expected="$(grep " $file\$" "$WORK/SHASUMS256.txt" | awk '{print $1}')"
  [ -n "$expected" ] && [ "$expected" = "$(sha256_of "$WORK/$file")" ] \
    || { echo "checksum mismatch for $file" >&2; exit 1; }
  tar -xzf "$WORK/$file" -C "$WORK" "$name/bin/node"
  echo "$WORK/$name/bin/node"
}

case "$(uname -s)-$(uname -m)" in
  Linux-x86_64) HOST=linux-x64 ;;
  Linux-aarch64) HOST=linux-arm64 ;;
  Darwin-arm64) HOST=darwin-arm64 ;;
  Darwin-x86_64) HOST=darwin-x64 ;;
  *) echo "unsupported build machine $(uname -s)-$(uname -m)" >&2; exit 1 ;;
esac

echo "bundling @realuptime/agent $VERSION for Node.js $NODE_VERSION"
( cd "$WORK" && npx --yes --package="$ESBUILD" esbuild "$AGENT/agent.ts" \
    --bundle --platform=node --format=cjs --target="node${NODE_VERSION%%.*}" \
    --outfile="$WORK/agent.cjs" --log-level=warning )

cat > "$WORK/sea-config.json" <<JSON
{ "main": "$WORK/agent.cjs", "output": "$WORK/agent.blob", "disableExperimentalSEAWarning": true }
JSON
HOST_NODE="$(fetch_node "$HOST")"
"$HOST_NODE" --experimental-sea-config "$WORK/sea-config.json" >/dev/null

for target in $TARGETS; do
  bin="$OUT/realuptime-agent-$VERSION-$target"
  cp "$(fetch_node "$target")" "$bin"
  chmod 0755 "$bin"
  case "$target" in
    darwin-*)
      # Only for checking a build on a Mac; releases ship Linux. macOS
      # needs the blob in its own Mach-O segment and an ad hoc signature.
      codesign --remove-signature "$bin"
      npx --yes --package="$POSTJECT" postject "$bin" NODE_SEA_BLOB "$WORK/agent.blob" --sentinel-fuse "$SEA_FUSE" --macho-segment-name NODE_SEA >/dev/null
      codesign --sign - "$bin"
      ;;
    *)
      npx --yes --package="$POSTJECT" postject "$bin" NODE_SEA_BLOB "$WORK/agent.blob" --sentinel-fuse "$SEA_FUSE" >/dev/null
      ;;
  esac
  echo "built $(basename "$bin")"
done
